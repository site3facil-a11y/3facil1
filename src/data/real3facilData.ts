// Helper para gerar URL completa da imagem hospedada em 3facil.com
export function get3FacilImageUrl(path: string): string {
  if (!path) return 'https://images.unsplash.com/photo-1560518883-ce09059eeffa?w=800&auto=format&fit=crop&q=80';
  if (path.startsWith('http')) return path;
  const clean = path.replace(/^\/?uploads\//, '');
  return `https://www.3facil.com/uploads/${clean}`;
}

